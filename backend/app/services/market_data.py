"""Market data: price observations, provider abstraction, CSV import and simulation.

Every observation carries its source so the UI can always tell the user what they are
looking at:

  manual     typed in by the user (e.g. read off the in-game transfer market)
  csv        imported from a CSV file the user supplied
  sample     demo history seeded with a demo account — not real FC 27 prices
  simulated  generated by the "simulate market move" tool — not real FC 27 prices
  live       fetched from an authorised provider configured via MARKET_DATA_PROVIDER

No live source is configured by default and none is assumed: see docs/MARKET_DATA.md.
"""

from __future__ import annotations

import csv
import io
import random
import re
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import Protocol

import httpx
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from ..config import Settings, get_settings
from ..db import utcnow
from ..models import Card, MarketPrice, User, WatchlistItem
from .common import ServiceError, get_settings_row, iso, not_found

SOURCES = ("manual", "csv", "sample", "simulated", "live")
SIMULATED_SOURCES = ("sample", "simulated")
HISTORY_WINDOW = timedelta(days=30)
MIN_HISTORY_POINTS = 3
MAX_PRICE = 15_000_000  # the in-game transfer market cap
MAX_CSV_ROWS = 5_000


# --------------------------------------------------------------------------- cards


def card_key(player_name: str, version: str | None = None, rating: int | None = None) -> str:
    parts = [player_name, version or "", str(rating or "")]
    return re.sub(r"[^a-z0-9]+", "-", "|".join(parts).lower()).strip("-")[:160]


def get_or_create_card(
    db: Session,
    user: User,
    player_name: str,
    *,
    version: str | None = None,
    rating: int | None = None,
    position: str | None = None,
    image_url: str | None = None,
    is_demo: bool = False,
) -> Card:
    player_name = (player_name or "").strip()
    if not player_name or len(player_name) > 120:
        raise ServiceError(422, "invalid_name", "Player name is required (max 120 characters).")
    if rating is not None and not 1 <= rating <= 99:
        raise ServiceError(422, "invalid_rating", "Rating must be between 1 and 99.")
    if image_url and not re.match(r"^https?://", image_url):
        raise ServiceError(422, "invalid_image", "Image URL must start with http:// or https://.")
    key = card_key(player_name, version, rating)
    card = db.scalar(select(Card).where(Card.user_id == user.id, Card.card_key == key))
    if card is None:
        card = Card(
            user_id=user.id,
            card_key=key,
            player_name=player_name,
            version=(version or None),
            rating=rating,
            position=(position or None),
            image_url=(image_url or None),
            is_demo=is_demo,
        )
        db.add(card)
        db.flush()
    else:
        if position:
            card.position = position
        if image_url:
            card.image_url = image_url
    return card


def get_card(db: Session, user: User, card_id: str) -> Card:
    card = db.get(Card, card_id)
    if card is None or card.user_id != user.id:
        raise not_found("Card")
    return card


def card_view(c: Card) -> dict:
    return {
        "id": c.id,
        "card_key": c.card_key,
        "player_name": c.player_name,
        "version": c.version,
        "rating": c.rating,
        "position": c.position,
        "image_url": c.image_url,
        "is_demo": c.is_demo,
    }


# --------------------------------------------------------------------------- price stats


def round_to_market_step(price: int) -> int:
    """Snap a price to the transfer market's bid increments."""
    if price < 1_000:
        step = 50
    elif price < 10_000:
        step = 100
    elif price < 50_000:
        step = 250
    elif price < 100_000:
        step = 500
    else:
        step = 1_000
    return max(step, int(round(price / step)) * step)


@dataclass
class PriceStats:
    latest_price: int | None
    latest_source: str | None
    latest_at: datetime | None
    historical_low: int | None
    historical_high: int | None
    history: list[int]
    points: int
    is_stale: bool
    age_hours: float | None

    def to_dict(self) -> dict:
        return {
            "latest_price": self.latest_price,
            "latest_source": self.latest_source,
            "latest_at": iso(self.latest_at),
            "historical_low": self.historical_low,
            "historical_high": self.historical_high,
            "points": self.points,
            "is_stale": self.is_stale,
            "age_hours": self.age_hours,
            "is_simulated": self.latest_source in SIMULATED_SOURCES if self.latest_source else None,
        }


def price_stats(db: Session, card: Card, *, platform: str, stale_after_hours: int, now: datetime | None = None) -> PriceStats:
    now = now or utcnow()
    rows = db.scalars(
        select(MarketPrice)
        .where(
            MarketPrice.card_id == card.id,
            MarketPrice.platform == platform,
            MarketPrice.observed_at >= now - HISTORY_WINDOW,
            MarketPrice.observed_at <= now + timedelta(minutes=5),
        )
        .order_by(MarketPrice.observed_at.asc(), MarketPrice.created_at.asc())
    ).all()
    latest = rows[-1] if rows else db.scalar(
        select(MarketPrice)
        .where(MarketPrice.card_id == card.id, MarketPrice.platform == platform)
        .order_by(MarketPrice.observed_at.desc())
        .limit(1)
    )
    history = [r.price for r in rows]
    enough = len(history) >= MIN_HISTORY_POINTS
    age = (now - latest.observed_at).total_seconds() / 3600 if latest else None
    return PriceStats(
        latest_price=latest.price if latest else None,
        latest_source=latest.source if latest else None,
        latest_at=latest.observed_at if latest else None,
        historical_low=min(history) if enough else None,
        historical_high=max(history) if enough else None,
        history=history,
        points=len(history),
        is_stale=age is None or age > stale_after_hours,
        age_hours=round(age, 2) if age is not None else None,
    )


def stats_for(db: Session, user: User, card: Card) -> PriceStats:
    s = get_settings_row(db, user)
    return price_stats(db, card, platform=s.platform, stale_after_hours=s.stale_after_hours)


# --------------------------------------------------------------------------- recording prices


def _validate_price(price) -> int:
    if not isinstance(price, int) or isinstance(price, bool) or price <= 0 or price > MAX_PRICE:
        raise ServiceError(422, "invalid_price", f"Price must be a whole number between 1 and {MAX_PRICE:,}.")
    return price


def record_price(
    db: Session,
    user: User,
    card: Card,
    price: int,
    *,
    source: str,
    observed_at: datetime | None = None,
    platform: str | None = None,
) -> MarketPrice:
    if source not in SOURCES:
        raise ServiceError(422, "invalid_source", "Unknown data source.")
    _validate_price(price)
    now = utcnow()
    observed_at = observed_at or now
    if observed_at.tzinfo is None:
        observed_at = observed_at.replace(tzinfo=timezone.utc)
    if observed_at > now + timedelta(minutes=5):
        raise ServiceError(422, "future_timestamp", "Observation time cannot be in the future.")
    obs = MarketPrice(
        card_id=card.id,
        platform=platform or get_settings_row(db, user).platform,
        price=price,
        source=source,
        observed_at=observed_at,
    )
    db.add(obs)
    return obs


def price_view(p: MarketPrice) -> dict:
    return {
        "id": p.id,
        "card_id": p.card_id,
        "platform": p.platform,
        "price": p.price,
        "source": p.source,
        "observed_at": iso(p.observed_at),
    }


def list_prices(db: Session, user: User, card_id: str, *, limit: int = 500) -> list[dict]:
    card = get_card(db, user, card_id)
    rows = db.scalars(
        select(MarketPrice).where(MarketPrice.card_id == card.id).order_by(MarketPrice.observed_at.desc()).limit(limit)
    ).all()
    return [price_view(p) for p in rows]


def delete_price(db: Session, user: User, price_id: str) -> None:
    p = db.get(MarketPrice, price_id)
    if p is None or db.get(Card, p.card_id).user_id != user.id:
        raise not_found("Price observation")
    if p.source == "live":
        raise ServiceError(422, "immutable_live", "Live provider observations cannot be deleted.")
    db.delete(p)
    db.commit()


def _parse_ts(raw: str) -> datetime:
    raw = raw.strip()
    try:
        dt = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except ValueError:
        dt = None
        for fmt in ("%d/%m/%Y %H:%M", "%d/%m/%Y", "%Y-%m-%d %H:%M"):
            try:
                dt = datetime.strptime(raw, fmt)
                break
            except ValueError:
                continue
        if dt is None:
            raise ValueError(f"unrecognised timestamp '{raw}'")
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)


def import_csv(db: Session, user: User, text: str) -> dict:
    """Import price history. Required columns: player_name, price. Optional: observed_at,
    platform, version, rating. Valid rows are imported in one transaction; invalid rows are
    reported back and skipped."""
    settings = get_settings_row(db, user)
    reader = csv.DictReader(io.StringIO(text.lstrip("﻿")))
    fields = {f.strip().lower() for f in (reader.fieldnames or [])}
    if not {"player_name", "price"} <= fields:
        raise ServiceError(422, "invalid_csv", "CSV needs a header row with at least player_name and price columns.")
    imported, errors = 0, []
    cards: set[str] = set()
    for i, raw in enumerate(reader, start=2):
        if i - 1 > MAX_CSV_ROWS:
            errors.append({"row": i, "error": f"Row limit of {MAX_CSV_ROWS:,} reached; remaining rows skipped."})
            break
        row = {(k or "").strip().lower(): (v or "").strip() for k, v in raw.items()}
        try:
            price = int(row["price"].replace(",", ""))
            observed = _parse_ts(row["observed_at"]) if row.get("observed_at") else utcnow()
            platform = row.get("platform") or settings.platform
            if platform not in ("cross", "playstation", "xbox", "pc"):
                raise ValueError(f"unknown platform '{platform}'")
            rating = int(row["rating"]) if row.get("rating") else None
            with db.begin_nested():
                card = get_or_create_card(db, user, row.get("player_name", ""), version=row.get("version"), rating=rating)
                record_price(db, user, card, price, source="csv", observed_at=observed, platform=platform)
            cards.add(card.id)
            imported += 1
        except (ValueError, KeyError, ServiceError) as exc:
            errors.append({"row": i, "error": getattr(exc, "message", str(exc))})
    db.commit()
    return {"imported": imported, "cards": len(cards), "errors": errors[:100], "error_count": len(errors)}


# --------------------------------------------------------------------------- simulation & sample data


def simulate_market_move(db: Session, user: User, *, seed: int | None = None) -> dict:
    """Append one simulated observation per watchlisted card (a small random walk).
    Clearly labelled 'simulated' — this is a practice tool, not a market feed."""
    rng = random.Random(seed)
    settings = get_settings_row(db, user)
    items = db.scalars(select(WatchlistItem).where(WatchlistItem.user_id == user.id)).all()
    created = []
    for item in items:
        stats = price_stats(db, item.card, platform=settings.platform, stale_after_hours=settings.stale_after_hours)
        base = stats.latest_price or round((item.target_buy + item.target_sell) / 2)
        drift = rng.uniform(-0.04, 0.04)
        price = round_to_market_step(max(200, round(base * (1 + drift))))
        created.append(record_price(db, user, item.card, price, source="simulated", platform=settings.platform))
    db.commit()
    return {"created": len(created), "prices": [price_view(p) for p in created]}


def seed_sample_history(
    db: Session,
    user: User,
    card: Card,
    *,
    low: int,
    high: int,
    current: int,
    days: int = 14,
    now: datetime | None = None,
    seed: int = 27,
) -> None:
    """Seed a deterministic demo history whose low/high are exactly `low`/`high` and whose
    latest observation is `current`. Marked source='sample'."""
    now = now or utcnow()
    rng = random.Random(seed)
    platform = get_settings_row(db, user).platform
    points = days * 2
    for i in range(points):
        t = now - timedelta(hours=12 * (points - i)) - timedelta(minutes=10)
        if i == points // 3:
            price = high
        elif i == (2 * points) // 3:
            price = low
        else:
            price = round_to_market_step(rng.randint(low + (high - low) // 6, high - (high - low) // 6))
        record_price(db, user, card, price, source="sample", observed_at=t, platform=platform)
    record_price(db, user, card, current, source="sample", observed_at=now - timedelta(minutes=5), platform=platform)


# --------------------------------------------------------------------------- providers


@dataclass
class ProviderQuote:
    card_key: str
    price: int
    observed_at: datetime


class MarketDataProvider(Protocol):
    name: str

    def fetch(self, card_keys: list[str], platform: str) -> list[ProviderQuote]: ...


class HttpJsonProvider:
    """Adapter for an authorised price API you have permission to use.

    Contract (see docs/MARKET_DATA.md):
      GET {MARKET_DATA_API_URL}?platform=<platform>&cards=<key1,key2,...>
      Authorization: Bearer {MARKET_DATA_API_KEY}
      -> {"prices": [{"card_key": "...", "price": 25200, "observed_at": "2026-10-10T12:00:00Z"}]}
    """

    name = "http_json"

    def __init__(self, url: str, api_key: str, timeout: float = 10.0, client: httpx.Client | None = None):
        self.url = url
        self.api_key = api_key
        self.timeout = timeout
        self.client = client

    def fetch(self, card_keys: list[str], platform: str) -> list[ProviderQuote]:
        headers = {"Authorization": f"Bearer {self.api_key}"} if self.api_key else {}
        params = {"platform": platform, "cards": ",".join(card_keys)}
        client = self.client or httpx.Client(timeout=self.timeout)
        try:
            resp = client.get(self.url, params=params, headers=headers)
            resp.raise_for_status()
            payload = resp.json()
        finally:
            if self.client is None:
                client.close()
        quotes = []
        for item in payload.get("prices", []):
            try:
                quotes.append(
                    ProviderQuote(
                        card_key=str(item["card_key"]),
                        price=_validate_price(int(item["price"])),
                        observed_at=_parse_ts(str(item["observed_at"])),
                    )
                )
            except (KeyError, ValueError, TypeError, ServiceError):
                continue  # skip malformed rows rather than storing bad data
        return quotes


def get_live_provider(settings: Settings | None = None) -> MarketDataProvider | None:
    settings = settings or get_settings()
    if settings.market_data_provider == "http_json" and settings.market_data_api_url:
        return HttpJsonProvider(
            settings.market_data_api_url, settings.market_data_api_key, settings.market_data_timeout_seconds
        )
    return None


def refresh_live(db: Session, user: User, provider: MarketDataProvider | None = None) -> dict:
    provider = provider or get_live_provider()
    if provider is None:
        raise ServiceError(
            409,
            "no_live_provider",
            "No authorised live market data provider is configured. Use manual entry, CSV import or simulation.",
        )
    settings = get_settings_row(db, user)
    cards = {c.card_key: c for c in db.scalars(select(Card).where(Card.user_id == user.id)).all()}
    if not cards:
        return {"updated": 0}
    try:
        quotes = provider.fetch(list(cards), settings.platform)
    except (httpx.HTTPError, ValueError) as exc:
        raise ServiceError(502, "provider_error", f"Live provider request failed: {exc.__class__.__name__}.") from exc
    updated = 0
    for q in quotes:
        card = cards.get(q.card_key)
        if card is not None:
            record_price(db, user, card, q.price, source="live", observed_at=q.observed_at, platform=settings.platform)
            updated += 1
    db.commit()
    return {"updated": updated, "provider": provider.name}


def data_status(db: Session, user: User) -> dict:
    """What kind of data is the user looking at, and how fresh is it?"""
    settings = get_settings_row(db, user)
    latest = db.scalar(
        select(MarketPrice)
        .join(Card, Card.id == MarketPrice.card_id)
        .where(Card.user_id == user.id, MarketPrice.platform == settings.platform)
        .order_by(MarketPrice.observed_at.desc())
        .limit(1)
    )
    counts = dict(
        db.execute(
            select(MarketPrice.source, func.count())
            .join(Card, Card.id == MarketPrice.card_id)
            .where(Card.user_id == user.id)
            .group_by(MarketPrice.source)
        ).all()
    )
    provider = get_live_provider()
    if latest is None:
        mode = "none"
    elif latest.source == "live":
        mode = "live"
    elif latest.source in ("manual", "csv"):
        mode = "manual"
    else:
        mode = "simulated"
    age = (utcnow() - latest.observed_at).total_seconds() / 3600 if latest else None
    return {
        "mode": mode,
        "trading_mode": settings.mode,
        "platform": settings.platform,
        "last_updated": iso(latest.observed_at) if latest else None,
        "last_source": latest.source if latest else None,
        "age_hours": round(age, 2) if age is not None else None,
        "is_stale": age is None or age > settings.stale_after_hours,
        "stale_after_hours": settings.stale_after_hours,
        "live_provider": provider.name if provider else None,
        "live_available": provider is not None,
        "observations_by_source": {k: int(v) for k, v in counts.items()},
    }
